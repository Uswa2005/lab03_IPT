# Task 1: Calculate Sum and Average of NumPy Array [5, 10, 15]

import numpy as np

# Create a NumPy array with numbers [5, 10, 15]
numbers = np.array([5, 10, 15])

# Display the array
print("Numbers:", numbers)

# Calculate and display the sum of array elements
print("Sum:", np.sum(numbers))

# Calculate and display the average (mean) of array elements
print("Average:", np.mean(numbers))
